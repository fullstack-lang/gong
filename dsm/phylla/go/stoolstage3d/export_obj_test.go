package stoolstage3d

import (
	"strconv"
	"strings"
	"testing"

	"github.com/fullstack-lang/gong/dsm/phylla/go/models"
)

func TestGenerateStoolOBJAndSTL(t *testing.T) {
	stage := models.NewStage("test")

	lib := (&models.Library{
		Name:              "MainLibrary",
		NbPixPerCharacter: 8.0,
	}).Stage(stage)

	plant := (&models.PlantAbstract{
		Name:               "TestStool",
		PlantType:          models.Stool,
		RhombusSideLength:  95.0,
		RhombusInsideAngle: 119.0,
		N:                  2,
		M:                  3,
		StackHeight:        2,
	}).Stage(stage)

	lib.Plants = append(lib.Plants, plant)

	stool := (&models.StoolAbstract{
		Name:                                   "TestStool-StoolAbstract",
		RadialRepetitions:                      3,
		RelativeTubeDiameter:                   0.042,
		RelativeHeight3DTorus:                  4.49,
		StoolTorusVerticalScale:                3.98,
		RelativeHeight:                         4.67,
		RelativeSeatThickness:                  0.72,
		ProjectionAngle:                        11.7,
		RelativeEyeSeparationCriteria:          0.40,
		RelativeEyeCornerControlVectorStrength: 0.23,
	}).Stage(stage)

	plant.StoolAbstract = stool

	updater := NewStool3DStageUpdater()
	stager := models.NewStagerForTest(stage)
	stager.SetStool3DUpdater(updater)
	stager.EnforceSemantic()

	// 1. Test Wavefront OBJ Export
	objContent := stager.GenerateStoolOBJ(plant)
	if objContent == "" {
		t.Fatalf("GenerateStoolOBJ returned empty string")
	}

	if !strings.Contains(objContent, "# Wavefront OBJ file generated by Phylla") {
		t.Errorf("Expected OBJ header comment not found")
	}
	if !strings.Contains(objContent, "o Stool_Seat") {
		t.Errorf("Expected object 'o Stool_Seat' not found in OBJ")
	}
	if !strings.Contains(objContent, "o Stool_Legs") {
		t.Errorf("Expected object 'o Stool_Legs' not found in OBJ")
	}

	// Validate 1-based indexing and syntax
	lines := strings.Split(objContent, "\n")
	vertexCount := 0
	faceCount := 0

	for lineNum, line := range lines {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(line, "v ") {
			vertexCount++
			parts := strings.Fields(line)
			if len(parts) != 4 {
				t.Fatalf("Line %d: invalid vertex line: %s", lineNum+1, line)
			}
			for i := 1; i <= 3; i++ {
				if _, err := strconv.ParseFloat(parts[i], 64); err != nil {
					t.Fatalf("Line %d: invalid float in vertex: %s", lineNum+1, line)
				}
			}
		} else if strings.HasPrefix(line, "f ") {
			faceCount++
			parts := strings.Fields(line)
			if len(parts) != 4 {
				t.Fatalf("Line %d: invalid triangle face line: %s", lineNum+1, line)
			}
			for i := 1; i <= 3; i++ {
				idx, err := strconv.Atoi(parts[i])
				if err != nil {
					t.Fatalf("Line %d: invalid face index integer: %s", lineNum+1, line)
				}
				if idx <= 0 {
					t.Fatalf("Line %d: face index must be >= 1 (1-based), got %d", lineNum+1, idx)
				}
				if idx > vertexCount {
					t.Fatalf("Line %d: face index %d exceeds currently defined vertices %d", lineNum+1, idx, vertexCount)
				}
			}
		}
	}

	t.Logf("OBJ validation successful: %d vertices, %d faces", vertexCount, faceCount)
	if vertexCount == 0 {
		t.Errorf("Expected vertices > 0, got %d", vertexCount)
	}
	if faceCount == 0 {
		t.Errorf("Expected faces > 0, got %d", faceCount)
	}

	// 2. Test STL Export
	stlContent := stager.GenerateStoolSTL(plant)
	if stlContent == "" {
		t.Fatalf("GenerateStoolSTL returned empty string")
	}

	if !strings.HasPrefix(stlContent, "solid TestStool\n") || !strings.HasSuffix(stlContent, "endsolid TestStool\n") {
		t.Errorf("Unexpected STL envelope")
	}

	facetsCount := strings.Count(stlContent, "facet normal")
	t.Logf("STL validation successful: %d facets", facetsCount)
	if facetsCount == 0 {
		t.Errorf("Expected facets > 0 in STL, got %d", facetsCount)
	}
}
