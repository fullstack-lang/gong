func TestGenerateStoolOBJAndSTL(t *testing.T) {
	stage := models.NewStage("test")

	lib := (&models.Library{
		Name:              "MainLibrary",
		NbPixPerCharacter: 8.0,
	}).Stage(stage)

	plant := (&models.PlantAbstract{
		Name:               "TestStool",
		PlantType:          models.Stool,
		RhombusSideLength:  95.0,
		RhombusInsideAngle: 119.0,
		N:                  2,
		M:                  3,
		StackHeight:        2,
	}).Stage(stage)

	lib.Plants = append(lib.Plants, plant)

	stoolStage := abstract_stool.NewStage("test_stool")
	stool := (&abstract_stool.StoolAbstract{
		Name:                                   "TestStool-StoolAbstract",
		RadialRepetitions:                      3,
		RelativeTubeDiameter:                   0.042,
		RelativeHeight3DTorus:                  4.49,
		StoolTorusVerticalScale:                3.98,
		RelativeHeight:                         4.67,
		RelativeSeatThickness:                  0.72,
		ProjectionAngle:                        11.7,
		RelativeEyeSeparationCriteria:          0.40,
		RelativeEyeCornerControlVectorStrength: 0.23,
	}).Stage(stoolStage)

	plant.StoolAbstract = stool

	updater := NewStool3DStageUpdater()
	stager := models.NewStagerForTest(stage)
	stager.SetStool3DUpdater(updater)
	stager.EnforceSemantic()

	// 1. Test Wavefront OBJ Export
	objContent := stager.GenerateStoolOBJ(plant)
	if objContent == "" {
		t.Fatalf("GenerateStoolOBJ returned empty string")
	}

	if !strings.Contains(objContent, "# Wavefront OBJ file generated by Phylla") {
		t.Errorf("Expected OBJ header comment not found")
	}
	if !strings.Contains(objContent, "o Stool_Seat") {
		t.Errorf("Expected object 'o Stool_Seat' not found in OBJ")
	}
	if !strings.Contains(objContent, "o Stool_Legs") {
		t.Errorf("Expected object 'o Stool_Legs' not found in OBJ")
	}

	// Validate 1-based indexing and syntax
	lines := strings.Split(objContent, "\n")
	vertexCount := 0
	faceCount := 0

	for lineNum, line := range lines {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(line, "v ") {
			vertexCount++
			parts := strings.Fields(line)
			if len(parts) != 4 {
				t.Fatalf("Line %d: invalid vertex line: %s", lineNum+1, line)
			}
			for i := 1; i <= 3; i++ {
				if _, err := strconv.ParseFloat(parts[i], 64); err != nil {
					t.Fatalf("Line %d: invalid float in vertex: %s", lineNum+1, line)
				}
			}
		} else if strings.HasPrefix(line, "f ") {
			faceCount++
			parts := strings.Fields(line)
			if len(parts) != 4 {
				t.Fatalf("Line %d: invalid triangle face line: %s", lineNum+1, line)
			}
			for i := 1; i <= 3; i++ {
				idx, err := strconv.Atoi(parts[i])
				if err != nil {
					t.Fatalf("Line %d: invalid face index integer: %s", lineNum+1, line)
				}
				if idx <= 0 {
					t.Fatalf("Line %d: face index must be >= 1 (1-based), got %d", lineNum+1, idx)
				}
				if idx > vertexCount {
					t.Fatalf("Line %d: face index %d exceeds currently defined vertices %d", lineNum+1, idx, vertexCount)
				}
			}
		}
	}

	t.Logf("OBJ validation successful: %d vertices, %d faces", vertexCount, faceCount)
	if vertexCount == 0 {
		t.Errorf("Expected vertices > 0, got %d", vertexCount)
	}
	if faceCount == 0 {
		t.Errorf("Expected faces > 0, got %d", faceCount)
	}

	// 2. Test STL Export
	stlContent := stager.GenerateStoolSTL(plant)
	if stlContent == "" {
		t.Fatalf("GenerateStoolSTL returned empty string")
	}

	if !strings.HasPrefix(stlContent, "solid TestStool\n") || !strings.HasSuffix(stlContent, "endsolid TestStool\n") {
		t.Errorf("Unexpected STL envelope")
	}

	facetsCount := strings.Count(stlContent, "facet normal")
	t.Logf("STL validation successful: %d facets", facetsCount)
	if facetsCount == 0 {
		t.Errorf("Expected facets > 0 in STL, got %d", facetsCount)
	}
}

func assertWatertightPositiveVolume(t *testing.T, label string, geom *threejs.BufferGeometry) float64 {
	t.Helper()
	if geom == nil || len(geom.Faces) == 0 {
		t.Fatalf("%s: empty geometry", label)
	}

	type vKey struct {
		x, y, z int64
	}
	quant := func(v *threejs.Vector3) vKey {
		return vKey{
			x: int64(math.Round(v.X * 1e5)),
			y: int64(math.Round(v.Y * 1e5)),
			z: int64(math.Round(v.Z * 1e5)),
		}
	}

	type halfEdge struct {
		a, b vKey
	}
	edges := make(map[halfEdge]int)
	signedVol6 := 0.0
	nonDegenerate := 0

	for idx, f := range geom.Faces {
		v1 := geom.Vertices[f.V1]
		v2 := geom.Vertices[f.V2]
		v3 := geom.Vertices[f.V3]
		k1, k2, k3 := quant(v1), quant(v2), quant(v3)
		if k1 == k2 || k2 == k3 || k3 == k1 {
			t.Fatalf("%s: degenerate triangle %d with duplicate vertex keys", label, idx)
		}
		edges[halfEdge{k1, k2}]++
		edges[halfEdge{k2, k3}]++
		edges[halfEdge{k3, k1}]++

		// 6 * signed volume contribution: v1 . (v2 x v3)
		cx := v2.Y*v3.Z - v2.Z*v3.Y
		cy := v2.Z*v3.X - v2.X*v3.Z
		cz := v2.X*v3.Y - v2.Y*v3.X
		signedVol6 += v1.X*cx + v1.Y*cy + v1.Z*cz
		nonDegenerate++
	}

	for he, count := range edges {
		if count != 1 {
			t.Fatalf("%s: non-manifold directed half-edge %+v has count %d (expected 1)", label, he, count)
		}
		opp := halfEdge{he.b, he.a}
		if edges[opp] != 1 {
			t.Fatalf("%s: boundary/unpaired half-edge %+v (opposite count %d)", label, he, edges[opp])
		}
	}

	vol := signedVol6 / 6.0
	if vol <= 0 {
		t.Fatalf("%s: expected strictly positive outward-oriented volume, got %f", label, vol)
	}
	t.Logf("%s: watertight manifold (%d triangles, volume = %.2f mm^3)", label, nonDegenerate, vol)
	return vol
}

func TestGrasshopperModeManifoldAndDXFExports(t *testing.T) {
	stage := models.NewStage("test_gh")

	lib := (&models.Library{
		Name:              "MainLibrary",
		NbPixPerCharacter: 8.0,
	}).Stage(stage)

	plant := (&models.PlantAbstract{
		Name:               "GrasshopperStool",
		PlantType:          models.Stool,
		RhombusSideLength:  95.0,
		RhombusInsideAngle: 119.0,
		N:                  2,
		M:                  3,
		StackHeight:        2,
	}).Stage(stage)
	lib.Plants = append(lib.Plants, plant)

	stoolStage := abstract_stool.NewStage("test_stool_gh")
	stool := (&abstract_stool.StoolAbstract{
		Name:                    "GrasshopperStool-StoolAbstract",
		RadialRepetitions:       3,
		RelativeTubeDiameter:    0.042,
		RelativeHeight3DTorus:   4.65,
		StoolTorusVerticalScale: 2.55,
		RelativeHeight:          4.74,
		RelativeSeatThickness:   0.832,
		ProjectionAngle:         8.5,
		IsGrasshopperMode:       true,
		InnerLegOffset:          0.1,
		LegFilletRadius:         0.2,
		SeatTopFilletRadius:     0.5,
		IsLegsReachTop:          false,
	}).Stage(stoolStage)
	plant.StoolAbstract = stool

	updater := NewStool3DStageUpdater()
	stager := models.NewStagerForTest(stage)
	stager.SetStool3DUpdater(updater)
	stager.EnforceSemantic()

	res := ComputeStoolGeometries(nil, stager, plant)
	if res == nil {
		t.Fatalf("ComputeStoolGeometries returned nil in Grasshopper mode")
	}

	assertWatertightPositiveVolume(t, "Grasshopper SeatGeom", res.SeatGeom)
	assertWatertightPositiveVolume(t, "Grasshopper LegsGeom", res.LegsGeom)

	// Verify the 0.2 leg fillet parameter produces active rolling-ball tip arcs (both top and bottom)
	// and remains watertight even at large fillet values (e.g., 1.2).
	if res.GrasshopperContours == nil || res.GrasshopperContours.LegBotContour == nil || !res.GrasshopperContours.LegBotContour.HasTipFillet {
		t.Fatalf("Expected active rolling-ball leg tip fillet for LegFilletRadius=0.2")
	}
	if res.GrasshopperContours.LegBotContour.AppliedFilletMM < 1.5 {
		t.Fatalf("Expected AppliedFilletMM >= 1.5 mm for LegFilletRadius=0.2, got %.3f mm", res.GrasshopperContours.LegBotContour.AppliedFilletMM)
	}
	t.Logf("LegFilletRadius=0.2 -> AppliedFilletMM = %.3f mm (top = %.3f mm)",
		res.GrasshopperContours.LegBotContour.AppliedFilletMM,
		res.GrasshopperContours.LegTopContour.AppliedFilletMM,
	)

	// Also verify large fillet bisection clamp never snaps back to 0 or breaks manifoldness.
	stool.LegFilletRadius = 1.2
	resLargeFillet := ComputeStoolGeometries(nil, stager, plant)
	if resLargeFillet == nil || resLargeFillet.GrasshopperContours == nil || !resLargeFillet.GrasshopperContours.LegBotContour.HasTipFillet {
		t.Fatalf("Expected bisection fallback to preserve active tip fillet at LegFilletRadius=1.2")
	}
	assertWatertightPositiveVolume(t, "Grasshopper LegsGeom (large fillet 1.2)", resLargeFillet.LegsGeom)
	stool.LegFilletRadius = 0.2

	// Validate 2D DXF export (four contour layers projected at Z=0).
	dxf2D := stager.GenerateStool2DDXF(plant)
	if dxf2D == "" {
		t.Fatalf("GenerateStool2DDXF returned empty string")
	}
	for _, layer := range []string{"SEAT_TOP", "SEAT_BOTTOM", "FEET_TOP", "FEET_BOTTOM"} {
		if !strings.Contains(dxf2D, "\n"+layer+"\n") {
			t.Errorf("2D DXF missing expected layer %s", layer)
		}
	}
	// Expect 1 SEAT_TOP + 1 SEAT_BOTTOM + 3 FEET_TOP + 3 FEET_BOTTOM = 8 closed POLYLINE entities.
	polyCount := strings.Count(dxf2D, "\nPOLYLINE\n")
	if polyCount != 8 {
		t.Errorf("Expected 8 closed POLYLINE entities in 2D DXF, got %d", polyCount)
	}

	// Validate 3D DXF export.
	dxf3D := stager.GenerateStool3DDXF(plant)
	if dxf3D == "" {
		t.Fatalf("GenerateStool3DDXF returned empty string")
	}
	if !strings.Contains(dxf3D, "\n3DFACE\n") || !strings.Contains(dxf3D, "\nSTOOL_SEAT\n") || !strings.Contains(dxf3D, "\nSTOOL_LEGS\n") {
		t.Errorf("3D DXF missing expected 3DFACE entities or layers")
	}

	// Validate Haussmannian Interior Blender (.py) script export (Matte Monolithic Oak & Walnut, 450 mm).
	blenderPy := stager.GenerateStoolHaussmannBlenderPy(plant)
	if blenderPy == "" {
		t.Fatalf("GenerateStoolHaussmannBlenderPy returned empty string")
	}
	for _, kw := range []string{"01_Haussmann_Oak_Stool", "02_Haussmann_Walnut_Stool", "MONOLITH_VERTS", "0.450000", "Valérie ROSTAING & Thomas PEUGOT"} {
		if !strings.Contains(blenderPy, kw) {
			t.Errorf("Haussmann Blender script missing expected token %q", kw)
		}
	}

	// Validate Manufacturing Cost-Estimation PDF Dossier export (450 mm monolithic, zero assembly assumed).
	pdfBytes := stager.GenerateStoolManufacturingPDF(plant)
	if len(pdfBytes) < 10000 {
		t.Fatalf("Expected substantial multi-page PDF dossier, got %d bytes", len(pdfBytes))
	}
	pdfStr := string(pdfBytes)
	if !strings.HasPrefix(pdfStr, "%PDF-1.4\n") || !strings.HasSuffix(pdfStr, "%%EOF\n") {
		t.Errorf("Invalid PDF header or EOF trailer")
	}
	if !strings.Contains(pdfStr, "/Count 4") {
		t.Errorf("Expected 4-page PDF dossier (/Count 4)")
	}
	if !strings.Contains(pdfStr, "ROSTAING & Thomas PEUGOT") {
		t.Errorf("Expected authors 'Valérie ROSTAING & Thomas PEUGOT' in PDF dossier")
	}
	if !strings.Contains(pdfStr, "450.0") {
		t.Errorf("Expected 450.0 mm height in PDF dossier")
	}
	if strings.Contains(strings.ToLower(pdfStr), "dowel") || strings.Contains(strings.ToLower(pdfStr), "domino") {
		t.Errorf("PDF dossier must not assume dowel/domino assembly")
	}
}
