var nonAlnumStoolSlugRe = regexp.MustCompile(`[^a-zA-Z0-9_-]+`)

func sanitizeStoolSlug(name string) string {
	s := strings.TrimSpace(name)
	s = nonAlnumStoolSlugRe.ReplaceAllString(s, "_")
	s = strings.Trim(s, "_")
	if s == "" {
		return "phylla_stool"
	}
	return s
}

func writePyMonolithicMeshData(sb *strings.Builder, combined *threejs.BufferGeometry, normScaleMMToM float64) {
	sb.WriteString("MONOLITH_VERTS = [\n")
	if combined != nil {
		for _, v := range combined.Vertices {
			// Map Three.js right-handed Y-up (X, Y, Z) [mm] -> Blender right-handed Z-up (X, -Z, Y) [m],
			// normalized to exact 0.450 m (450 mm) stool height.
			bx := v.X * normScaleMMToM
			by := -v.Z * normScaleMMToM
			bz := v.Y * normScaleMMToM
			sb.WriteString(fmt.Sprintf("    (%.6f, %.6f, %.6f),\n", bx, by, bz))
		}
	}
	sb.WriteString("]\n\n")

	sb.WriteString("MONOLITH_FACES = [\n")
	if combined != nil {
		for i, f := range combined.Faces {
			if i%6 == 0 {
				sb.WriteString("    ")
			}
			sb.WriteString(fmt.Sprintf("(%d, %d, %d),", f.V1, f.V2, f.V3))
			if i%6 == 5 || i == len(combined.Faces)-1 {
				sb.WriteByte('\n')
			} else {
				sb.WriteByte(' ')
			}
		}
	}
	sb.WriteString("]\n\n")
}

