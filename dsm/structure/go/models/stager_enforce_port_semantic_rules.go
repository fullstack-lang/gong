package models

import (
	"fmt"
	"time"
)

func (stager *Stager) buildSystemAndPartLibraryMaps() (
	systemToLibrary map[*System]*Library,
	partToLibrary map[*Part]*Library,
) {
	systemToLibrary = make(map[*System]*Library)
	partToLibrary = make(map[*Part]*Library)

	var visitSystem func(lib *Library, sys *System)
	visitSystem = func(lib *Library, sys *System) {
		if sys == nil {
			return
		}
		if _, visited := systemToLibrary[sys]; visited {
			return
		}
		systemToLibrary[sys] = lib
		for _, part := range sys.Parts {
			if part != nil {
				partToLibrary[part] = lib
			}
		}
		for _, extPart := range sys.ExternalParts {
			if extPart != nil {
				partToLibrary[extPart] = lib
			}
		}
		for _, sub := range sys.SubSystemes {
			visitSystem(lib, sub)
		}
	}

	for _, library := range stager.stage.GetInstancesSorted[*Library]() {
		for _, sys := range library.RootSystemes {
			visitSystem(library, sys)
		}
	}

	return
}

func (stager *Stager) findSystemLibrary(sys *System) *Library {
	systemToLibrary, _ := stager.buildSystemAndPartLibraryMaps()
	if lib, ok := systemToLibrary[sys]; ok {
		return lib
	}
	if sys != nil && sys.GetOwningLibrary() != nil {
		return sys.GetOwningLibrary()
	}
	return stager.getRootLibrary()
}

func (stager *Stager) enforcePortSemanticRules() (needCommit bool) {
	_, partToLibrary := stager.buildSystemAndPartLibraryMaps()

	for _, part := range stager.stage.GetInstancesSorted[*Part]() {
		if part.TypeOfPart != nil && !part.IsPartNameNotSystemName && part.GetName() != part.TypeOfPart.GetName() {
			oldName := part.GetName()
			part.SetName(part.TypeOfPart.GetName())
			needCommit = true
			if stager.probeForm != nil {
				stager.probeForm.AddNotification(time.Now(), fmt.Sprintf("Part \"%s\" name overridden to \"%s\"",
					oldName, part.GetName()))
			}
		}
	}

	autoNamedPorts := make(map[*Port]bool)
	for _, part := range stager.stage.GetInstancesSorted[*Part]() {
		lib := partToLibrary[part]
		if lib == nil {
			lib = part.GetOwningLibrary()
		}
		if lib == nil || !lib.IsPortAndDataFlowNamesAutoGenerated {
			continue
		}

		for idx, port := range part.Ports {
			if port == nil {
				continue
			}
			autoNamedPorts[port] = true
			var expectedPortName string
			if part.GetName() != "" {
				expectedPortName = fmt.Sprintf("%s-P%d", part.GetName(), idx+1)
			} else {
				expectedPortName = fmt.Sprintf("P%d", idx+1)
			}
			if port.GetName() != expectedPortName {
				oldName := port.GetName()
				port.SetName(expectedPortName)
				needCommit = true
				if stager.probeForm != nil {
					stager.probeForm.AddNotification(time.Now(), fmt.Sprintf("Port \"%s\" renamed to \"%s\"",
						oldName, expectedPortName))
				}
			}
		}
	}

	if len(autoNamedPorts) > 0 {
		for _, diagram := range stager.stage.GetInstancesSorted[*DiagramStructure]() {
			for _, portShape := range diagram.Port_Shapes {
				if portShape.Port != nil && autoNamedPorts[portShape.Port] {
					expectedShapeName := portShape.Port.GetName() + "-" + diagram.GetName()
					if portShape.Name != expectedShapeName {
						portShape.Name = expectedShapeName
						needCommit = true
					}
				}
			}
		}
	}

	return
}
