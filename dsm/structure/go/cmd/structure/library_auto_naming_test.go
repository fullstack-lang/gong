package main

import (
	"slices"
	"testing"

	"github.com/fullstack-lang/gong/dsm/structure/go/level1stack"
	"github.com/fullstack-lang/gong/dsm/structure/go/models"
	form "github.com/fullstack-lang/gong/lib/form/go/models"
	svg "github.com/fullstack-lang/gong/lib/svg/go/models"
)

func TestLibraryPortAndDataFlowAutoGeneratedNames(t *testing.T) {
	stack := level1stack.NewLevel1StackDelta("test_library_auto_naming", "", "", true, true, false)
	stager := models.NewStager(
		stack.R,
		stack.Stage,
		stack.Probe,
	)
	stage := stack.Stage
	rootLib := stager.GetRootLibrary()

	if rootLib.IsPortAndDataFlowNamesAutoGenerated {
		t.Fatalf("expected IsPortAndDataFlowNamesAutoGenerated to default to false")
	}

	sys := (&models.System{Name: "MainSystem"}).Stage(stage)
	rootLib.RootSystemes = append(rootLib.RootSystemes, sys)

	partA := (&models.Part{Name: "A"}).Stage(stage)
	partB := (&models.Part{Name: "B"}).Stage(stage)
	extC := (&models.Part{Name: "ExtC"}).Stage(stage)
	sys.Parts = append(sys.Parts, partA, partB)
	sys.ExternalParts = append(sys.ExternalParts, extC)

	portA1 := (&models.Port{Name: "CustomPortA1"}).Stage(stage)
	portA2 := (&models.Port{Name: "CustomPortA2"}).Stage(stage)
	portB1 := (&models.Port{Name: "CustomPortB1"}).Stage(stage)
	partA.Ports = append(partA.Ports, portA1, portA2)
	partB.Ports = append(partB.Ports, portB1)

	dfPort2Port := (&models.DataFlow{
		Name:      "CustomDF1",
		Type:      models.DataFlow_Port2Port,
		StartPort: portA1,
		EndPort:   portB1,
	}).Stage(stage)
	dfExt2Port := (&models.DataFlow{
		Name:              "CustomDF2",
		Type:              models.DataFlow_ExternalPart2Port,
		StartExternalPart: extC,
		EndPort:           portB1,
	}).Stage(stage)
	dfPort2Ext := (&models.DataFlow{
		Name:            "CustomDF3",
		Type:            models.DataFlow_Port2ExternalPart,
		StartPort:       portA2,
		EndExternalPart: extC,
	}).Stage(stage)
	rootLib.RootDataFlows = append(rootLib.RootDataFlows, dfPort2Port, dfExt2Port, dfPort2Ext)
	sys.DataFlows = append(sys.DataFlows, dfPort2Port, dfExt2Port, dfPort2Ext)

	diag := (&models.DiagramStructure{
		Name:        "Diag1",
		IsChecked:   true,
		IsEditable_: true,
		Width:       1200,
		Height:      900,
	}).Stage(stage)
	sys.DiagramStructures = append(sys.DiagramStructures, diag)

	sysShape := (&models.SystemShape{
		Name:   "MainSystem-Diag1",
		System: sys,
		RectShape: models.RectShape{
			X: 50, Y: 50, Width: 800, Height: 600,
		},
	}).Stage(stage)
	diag.System_Shapes = append(diag.System_Shapes, sysShape)

	partAShape := (&models.PartShape{
		Name: "A-Diag1",
		Part: partA,
		RectShape: models.RectShape{
			X: 100, Y: 150, Width: 200, Height: 120,
		},
	}).Stage(stage)
	partBShape := (&models.PartShape{
		Name: "B-Diag1",
		Part: partB,
		RectShape: models.RectShape{
			X: 450, Y: 150, Width: 200, Height: 120,
		},
	}).Stage(stage)
	diag.Part_Shapes = append(diag.Part_Shapes, partAShape, partBShape)

	extCShape := (&models.ExternalPartShape{
		Name: "ExtC-Diag1",
		Part: extC,
		RectShape: models.RectShape{
			X: 900, Y: 150, Width: 150, Height: 80,
		},
	}).Stage(stage)
	diag.ExternalPart_Shapes = append(diag.ExternalPart_Shapes, extCShape)

	portA1Shape := (&models.PortShape{
		Name: "CustomPortA1-Diag1",
		Port: portA1,
		RectShape: models.RectShape{
			X: 280, Y: 170, Width: 40, Height: 40,
		},
	}).Stage(stage)
	portA2Shape := (&models.PortShape{
		Name: "CustomPortA2-Diag1",
		Port: portA2,
		RectShape: models.RectShape{
			X: 280, Y: 220, Width: 40, Height: 40,
		},
	}).Stage(stage)
	portB1Shape := (&models.PortShape{
		Name: "CustomPortB1-Diag1",
		Port: portB1,
		RectShape: models.RectShape{
			X: 430, Y: 190, Width: 40, Height: 40,
		},
	}).Stage(stage)
	diag.Port_Shapes = append(diag.Port_Shapes, portA1Shape, portA2Shape, portB1Shape)

	dfShape1 := (&models.DataFlowShape{
		Name:     "CustomDF1",
		DataFlow: dfPort2Port,
	}).Stage(stage)
	diag.DataFlow_Shapes = append(diag.DataFlow_Shapes, dfShape1)

	stage.Commit()

	// 1. Manual names are preserved when IsPortAndDataFlowNamesAutoGenerated is false
	if portA1.Name != "CustomPortA1" || portA2.Name != "CustomPortA2" || portB1.Name != "CustomPortB1" {
		t.Fatalf("expected manual port names preserved when option disabled, got %q, %q, %q", portA1.Name, portA2.Name, portB1.Name)
	}
	if dfPort2Port.Name != "CustomDF1" || dfExt2Port.Name != "CustomDF2" || dfPort2Ext.Name != "CustomDF3" {
		t.Fatalf("expected manual data flow names preserved when option disabled, got %q, %q, %q", dfPort2Port.Name, dfExt2Port.Name, dfPort2Ext.Name)
	}

	// 2. Enable IsPortAndDataFlowNamesAutoGenerated via the Library Probe Form
	stack.Probe.FillUpFormFromGongstruct(rootLib, "Library")
	formStage := stack.Probe.GetFormStage()
	fg := formStage.GetInstancesSorted[*form.FormGroup]()[0]
	var foundOptionField bool
	for _, fd := range fg.FormDivs {
		if fd.Name == "IsPortAndDataFlowNamesAutoGenerated" && len(fd.CheckBoxs) > 0 && fd.CheckBoxs[0] != nil {
			fd.CheckBoxs[0].Value = true
			foundOptionField = true
			break
		}
	}
	if !foundOptionField {
		t.Fatalf("expected IsPortAndDataFlowNamesAutoGenerated boolean field in Library form")
	}
	formStage.Commit()
	fg.OnSave.OnSave()

	if !rootLib.IsPortAndDataFlowNamesAutoGenerated {
		t.Fatalf("expected rootLib.IsPortAndDataFlowNamesAutoGenerated to be true after form save")
	}
	if portA1.Name != "A-P1" || portA2.Name != "A-P2" || portB1.Name != "B-P1" {
		t.Fatalf("expected generated port names A-P1, A-P2, B-P1; got %q, %q, %q", portA1.Name, portA2.Name, portB1.Name)
	}
	if portA1Shape.Name != "A-P1-Diag1" || portA2Shape.Name != "A-P2-Diag1" || portB1Shape.Name != "B-P1-Diag1" {
		t.Fatalf("expected PortShape names synced, got %q, %q, %q", portA1Shape.Name, portA2Shape.Name, portB1Shape.Name)
	}
	if dfPort2Port.Name != "A-P1-B-P1" {
		t.Fatalf("expected Port2Port DataFlow name %q, got %q", "A-P1-B-P1", dfPort2Port.Name)
	}
	if dfShape1.Name != "A-P1-B-P1" {
		t.Fatalf("expected DataFlowShape name %q, got %q", "A-P1-B-P1", dfShape1.Name)
	}
	if dfExt2Port.Name != "ExtC-B-P1" {
		t.Fatalf("expected ExternalPart2Port DataFlow name %q, got %q", "ExtC-B-P1", dfExt2Port.Name)
	}
	if dfPort2Ext.Name != "A-P2-ExtC" {
		t.Fatalf("expected Port2ExternalPart DataFlow name %q, got %q", "A-P2-ExtC", dfPort2Ext.Name)
	}

	// Verify SVG rect names reflect generated port names
	svgObj := stager.GetSvgObject()
	var rectNames []string
	for _, r := range svgObj.Layers[0].Rects {
		rectNames = append(rectNames, r.Name)
	}
	for _, expectedRect := range []string{"A-P1", "A-P2", "B-P1"} {
		if !slices.Contains(rectNames, expectedRect) {
			t.Errorf("expected SVG rect %q in %v", expectedRect, rectNames)
		}
	}
	_ = svg.SVG{}

	// 3. Renaming Parts and removing a Port dynamically regenerates Port and DataFlow names
	partA.Name = "Radar"
	partB.Name = "Tracker"
	stage.Commit()

	if portA1.Name != "Radar-P1" || portA2.Name != "Radar-P2" || portB1.Name != "Tracker-P1" {
		t.Fatalf("expected regenerated port names after Part rename, got %q, %q, %q", portA1.Name, portA2.Name, portB1.Name)
	}
	if dfPort2Port.Name != "Radar-P1-Tracker-P1" || dfPort2Ext.Name != "Radar-P2-ExtC" {
		t.Fatalf("expected regenerated DataFlow names after Part rename, got %q, %q", dfPort2Port.Name, dfPort2Ext.Name)
	}

	// Remove portA1 -> portA2 shifts to index 1 ("Radar-P1") and dfPort2Ext updates to "Radar-P1-ExtC"
	partA.Ports = []*models.Port{portA2}
	stage.Commit()
	if portA2.Name != "Radar-P1" {
		t.Fatalf("expected remaining port to re-index to Radar-P1, got %q", portA2.Name)
	}
	if dfPort2Ext.Name != "Radar-P1-ExtC" {
		t.Fatalf("expected dfPort2Ext to regenerate to Radar-P1-ExtC, got %q", dfPort2Ext.Name)
	}

	// 4. SubLibrary with IsPortAndDataFlowNamesAutoGenerated == false preserves its own manual names
	subLib := (&models.Library{
		Name:                                "SubLib",
		IsPortAndDataFlowNamesAutoGenerated: false,
	}).Stage(stage)
	rootLib.SubLibraries = append(rootLib.SubLibraries, subLib)

	subSys := (&models.System{Name: "SubSys"}).Stage(stage)
	subLib.RootSystemes = append(subLib.RootSystemes, subSys)
	subPart1 := (&models.Part{Name: "SubA"}).Stage(stage)
	subPart2 := (&models.Part{Name: "SubB"}).Stage(stage)
	subSys.Parts = append(subSys.Parts, subPart1, subPart2)
	subPort1 := (&models.Port{Name: "ManualSubPort1"}).Stage(stage)
	subPort2 := (&models.Port{Name: "ManualSubPort2"}).Stage(stage)
	subPart1.Ports = append(subPart1.Ports, subPort1)
	subPart2.Ports = append(subPart2.Ports, subPort2)
	subDF := (&models.DataFlow{
		Name:      "ManualSubFlow",
		Type:      models.DataFlow_Port2Port,
		StartPort: subPort1,
		EndPort:   subPort2,
	}).Stage(stage)
	subLib.RootDataFlows = append(subLib.RootDataFlows, subDF)
	subSys.DataFlows = append(subSys.DataFlows, subDF)
	stage.Commit()

	if subPort1.Name != "ManualSubPort1" || subDF.Name != "ManualSubFlow" {
		t.Fatalf("expected SubLib manual names preserved, got port=%q df=%q", subPort1.Name, subDF.Name)
	}

	// 5. Disabling option on rootLib preserves subsequent manual edits
	rootLib.IsPortAndDataFlowNamesAutoGenerated = false
	portB1.Name = "ManualTrackerPort"
	dfExt2Port.Name = "ManualExtFlow"
	stage.Commit()

	if portB1.Name != "ManualTrackerPort" || dfExt2Port.Name != "ManualExtFlow" {
		t.Fatalf("expected manual edits preserved after disabling option, got port=%q df=%q", portB1.Name, dfExt2Port.Name)
	}
}
