func TestATCCExampleStageCoverageAndSemantics(t *testing.T) {
	if os.Getenv("GENERATE_ATCC_STAGE") == "1" {
		genStack, _ := buildATCCExampleStage(t)
		genStack.Stage.MarshallFile("data/stage.go", "github.com/fullstack-lang/gong/dsm/structure/go/models", "main")
	}

	stack := level1stack.NewLevel1StackDelta("test_loaded_atcc_stage", "data/stage.go", "", true, true, false)
	stager := models.NewStager(
		stack.R,
		stack.Stage,
		stack.Probe,
	)
	stage := stack.Stage

	// Verify all 28 Gongstruct types in dsm/structure have populated instances in data/stage.go
	checks := []struct {
		name  string
		count int
	}{
		{"Library", len(stage.GetInstancesSorted[*models.Library]())},
		{"System", len(stage.GetInstancesSorted[*models.System]())},
		{"Part", len(stage.GetInstancesSorted[*models.Part]())},
		{"PartAnchoredPath", len(stage.GetInstancesSorted[*models.PartAnchoredPath]())},
		{"Port", len(stage.GetInstancesSorted[*models.Port]())},
		{"DataFlow", len(stage.GetInstancesSorted[*models.DataFlow]())},
		{"ControlFlow", len(stage.GetInstancesSorted[*models.ControlFlow]())},
		{"Data", len(stage.GetInstancesSorted[*models.Data]())},
		{"Protocol", len(stage.GetInstancesSorted[*models.Protocol]())},
		{"ProtocolLayer", len(stage.GetInstancesSorted[*models.ProtocolLayer]())},
		{"Resource", len(stage.GetInstancesSorted[*models.Resource]())},
		{"Note", len(stage.GetInstancesSorted[*models.Note]())},
		{"SemanticTag", len(stage.GetInstancesSorted[*models.SemanticTag]())},
		{"LayerDefinition", len(stage.GetInstancesSorted[*models.LayerDefinition]())},
		{"DiagramStructure", len(stage.GetInstancesSorted[*models.DiagramStructure]())},
		{"DiagramLayerState", len(stage.GetInstancesSorted[*models.DiagramLayerState]())},
		{"SystemShape", len(stage.GetInstancesSorted[*models.SystemShape]())},
		{"PartShape", len(stage.GetInstancesSorted[*models.PartShape]())},
		{"ExternalPartShape", len(stage.GetInstancesSorted[*models.ExternalPartShape]())},
		{"PortShape", len(stage.GetInstancesSorted[*models.PortShape]())},
		{"DataFlowShape", len(stage.GetInstancesSorted[*models.DataFlowShape]())},
		{"ControlPointShape", len(stage.GetInstancesSorted[*models.ControlPointShape]())},
		{"ControlFlowShape", len(stage.GetInstancesSorted[*models.ControlFlowShape]())},
		{"DataShape", len(stage.GetInstancesSorted[*models.DataShape]())},
		{"ProtocolShape", len(stage.GetInstancesSorted[*models.ProtocolShape]())},
		{"ProtocolLayerShape", len(stage.GetInstancesSorted[*models.ProtocolLayerShape]())},
		{"AllocatedResourceShape", len(stage.GetInstancesSorted[*models.AllocatedResourceShape]())},
		{"AllocatedSystemShape", len(stage.GetInstancesSorted[*models.AllocatedSystemShape]())},
		{"NoteShape", len(stage.GetInstancesSorted[*models.NoteShape]())},
		{"NotePartShape", len(stage.GetInstancesSorted[*models.NotePartShape]())},
		{"NotePortShape", len(stage.GetInstancesSorted[*models.NotePortShape]())},
		{"NoteDataFlowShape", len(stage.GetInstancesSorted[*models.NoteDataFlowShape]())},
	}
	for _, c := range checks {
		if c.count == 0 {
			t.Errorf("expected at least 1 staged instance of %s in data/stage.go, got 0", c.name)
		}
	}

	// Verify active diagram renders SVG cleanly with rects, links, and RectLinkLinks
	svgObj := stager.GetSvgObject()
	if svgObj == nil || len(svgObj.Layers) == 0 {
		t.Fatalf("expected non-empty SVG object on active diagram")
	}
	layer := svgObj.Layers[0]
	if len(layer.Rects) < 20 || len(layer.Links) < 12 || len(layer.RectLinkLinks) < 1 {
		t.Fatalf("unexpectedly sparse SVG on active diagram: rects=%d links=%d rectLinkLinks=%d",
			len(layer.Rects), len(layer.Links), len(layer.RectLinkLinks))
	}

	// Switch across every diagram to ensure every single diagram renders without panic or orphan loss
	diagrams := stage.GetInstancesSorted[*models.DiagramStructure]()
	if len(diagrams) != 6 {
		t.Fatalf("expected 6 curated DiagramStructures, got %d", len(diagrams))
	}
	for _, d := range diagrams {
		for _, other := range diagrams {
			other.IsChecked = (other == d)
		}
		stage.Commit()
		s := stager.GetSvgObject()
		if s == nil || len(s.Layers) == 0 || len(s.Layers[0].Rects) < 3 {
			t.Fatalf("diagram %q failed to render valid SVG rects", d.Name)
		}
	}
}
