package main

import (
	"slices"
	"testing"

	"github.com/fullstack-lang/gong/dsm/structure/go/level1stack"
	"github.com/fullstack-lang/gong/dsm/structure/go/models"
	form "github.com/fullstack-lang/gong/lib/form/go/models"
	tree "github.com/fullstack-lang/gong/lib/tree/go/models"
)

func findTreeNodeByName(nodes []*tree.Node, name string) *tree.Node {
	for _, n := range nodes {
		if n.Name == name {
			return n
		}
		if found := findTreeNodeByName(n.Children, name); found != nil {
			return found
		}
	}
	return nil
}

func TestProtocolAbstractConcreteSemanticAndAutoNaming(t *testing.T) {
	stack := level1stack.NewLevel1StackDelta("test_protocol", "", "", true, true, false)
	stager := models.NewStager(
		stack.R,
		stack.Stage,
		stack.Probe,
	)
	stage := stack.Stage
	rootLib := stager.GetRootLibrary()
	rootLib.IsPortAndDataFlowNamesAutoGenerated = true

	// 1. Define ProtocolLayers and Protocols (orphan protocol/layer should also auto-attach to rootLib)
	layerREST := (&models.ProtocolLayer{Name: "REST"}).Stage(stage)
	layerIP := (&models.ProtocolLayer{Name: "IP"}).Stage(stage)
	layerEth := (&models.ProtocolLayer{Name: "Ethernet"}).Stage(stage)
	layerHTTP2 := (&models.ProtocolLayer{Name: "HTTP2"}).Stage(stage)

	protoHTTP := (&models.Protocol{
		Name:           "HTTP",
		ProtocolLayers: []*models.ProtocolLayer{layerREST, layerIP, layerEth},
	}).Stage(stage)
	protoGRPC := (&models.Protocol{
		Name:           "gRPC",
		ProtocolLayers: []*models.ProtocolLayer{layerHTTP2, layerIP},
	}).Stage(stage)

	// 2. Build System, Parts, Ports, ExternalPart, DataFlows, and Diagram
	sys := (&models.System{Name: "Sys"}).Stage(stage)
	rootLib.RootSystemes = append(rootLib.RootSystemes, sys)

	partA := (&models.Part{Name: "A"}).Stage(stage)
	partB := (&models.Part{Name: "B"}).Stage(stage)
	extC := (&models.Part{Name: "ExtC"}).Stage(stage)
	sys.Parts = append(sys.Parts, partA, partB)
	sys.ExternalParts = append(sys.ExternalParts, extC)

	// Set Protocol ONLY on portA1 initially to verify semantic propagation to df1 and portB1
	portA1 := (&models.Port{Name: "initA1", Protocol: protoHTTP}).Stage(stage)
	portA2 := (&models.Port{Name: "initA2"}).Stage(stage)
	portB1 := (&models.Port{Name: "initB1"}).Stage(stage)
	partA.Ports = append(partA.Ports, portA1, portA2)
	partB.Ports = append(partB.Ports, portB1)

	df1 := (&models.DataFlow{
		Name:      "initDF1",
		Type:      models.DataFlow_Port2Port,
		StartPort: portA1,
		EndPort:   portB1,
	}).Stage(stage)

	// Set Protocol ONLY on df2 (Port2ExternalPart) to verify propagation back to portA2
	df2 := (&models.DataFlow{
		Name:            "initDF2",
		Type:            models.DataFlow_Port2ExternalPart,
		StartPort:       portA2,
		EndExternalPart: extC,
		Protocol:        protoGRPC,
	}).Stage(stage)

	rootLib.RootDataFlows = append(rootLib.RootDataFlows, df1, df2)
	sys.DataFlows = append(sys.DataFlows, df1, df2)

	diag := (&models.DiagramStructure{
		Name:        "Diag1",
		IsChecked:   true,
		IsEditable_: true,
		Width:       1200,
		Height:      900,
	}).Stage(stage)
	sys.DiagramStructures = append(sys.DiagramStructures, diag)

	sysShape := (&models.SystemShape{
		Name:      "Sys-Diag1",
		System:    sys,
		RectShape: models.RectShape{X: 50, Y: 50, Width: 800, Height: 600},
	}).Stage(stage)
	diag.System_Shapes = append(diag.System_Shapes, sysShape)

	partAShape := (&models.PartShape{
		Name:      "A-Diag1",
		Part:      partA,
		RectShape: models.RectShape{X: 100, Y: 150, Width: 200, Height: 140},
	}).Stage(stage)
	partBShape := (&models.PartShape{
		Name:      "B-Diag1",
		Part:      partB,
		RectShape: models.RectShape{X: 450, Y: 150, Width: 200, Height: 140},
	}).Stage(stage)
	diag.Part_Shapes = append(diag.Part_Shapes, partAShape, partBShape)

	extCShape := (&models.ExternalPartShape{
		Name:      "ExtC-Diag1",
		Part:      extC,
		RectShape: models.RectShape{X: 900, Y: 150, Width: 150, Height: 80},
	}).Stage(stage)
	diag.ExternalPart_Shapes = append(diag.ExternalPart_Shapes, extCShape)

	portA1Shape := (&models.PortShape{
		Name:      "initA1-Diag1",
		Port:      portA1,
		RectShape: models.RectShape{X: 280, Y: 170, Width: 40, Height: 40},
	}).Stage(stage)
	portA2Shape := (&models.PortShape{
		Name:      "initA2-Diag1",
		Port:      portA2,
		RectShape: models.RectShape{X: 280, Y: 230, Width: 40, Height: 40},
	}).Stage(stage)
	portB1Shape := (&models.PortShape{
		Name:      "initB1-Diag1",
		Port:      portB1,
		RectShape: models.RectShape{X: 430, Y: 170, Width: 40, Height: 40},
	}).Stage(stage)
	diag.Port_Shapes = append(diag.Port_Shapes, portA1Shape, portA2Shape, portB1Shape)

	df1Shape := (&models.DataFlowShape{
		Name:     "initDF1",
		DataFlow: df1,
	}).Stage(stage)
	df2Shape := (&models.DataFlowShape{
		Name:     "initDF2",
		DataFlow: df2,
	}).Stage(stage)
	diag.DataFlow_Shapes = append(diag.DataFlow_Shapes, df1Shape, df2Shape)

	stage.Commit()

	// Verify orphan reattachment to rootLib
	if !slices.Contains(rootLib.RootProtocols, protoHTTP) || !slices.Contains(rootLib.RootProtocols, protoGRPC) {
		t.Fatalf("expected protocols reattached to rootLib.RootProtocols, got %v", rootLib.RootProtocols)
	}
	if len(rootLib.RootProtocolLayers) != 4 {
		t.Fatalf("expected 4 protocol layers in rootLib.RootProtocolLayers, got %d", len(rootLib.RootProtocolLayers))
	}

	// Verify semantic propagation: portA1 (HTTP) -> df1 & portB1; df2 (gRPC) -> portA2
	if df1.Protocol != protoHTTP || portB1.Protocol != protoHTTP {
		t.Fatalf("expected df1 and portB1 protocol to be synchronized to HTTP, got df1=%v portB1=%v", df1.Protocol, portB1.Protocol)
	}
	if portA2.Protocol != protoGRPC {
		t.Fatalf("expected portA2 protocol to be synchronized to gRPC, got %v", portA2.Protocol)
	}

	// Verify auto-generated names with protocol suffix (no triple repetition on DataFlow)
	if portA1.Name != "A-P1-HTTP" || portB1.Name != "B-P1-HTTP" || portA2.Name != "A-P2-gRPC" {
		t.Fatalf("unexpected port names: portA1=%q portB1=%q portA2=%q", portA1.Name, portB1.Name, portA2.Name)
	}
	if df1.Name != "A-P1-B-P1-HTTP" {
		t.Fatalf("expected df1 name %q, got %q", "A-P1-B-P1-HTTP", df1.Name)
	}
	if df1Shape.Name != "A-P1-B-P1-HTTP" {
		t.Fatalf("expected df1Shape name %q, got %q", "A-P1-B-P1-HTTP", df1Shape.Name)
	}
	if df2.Name != "A-P2-ExtC-gRPC" {
		t.Fatalf("expected df2 name %q, got %q", "A-P2-ExtC-gRPC", df2.Name)
	}

	// 3. Concrete syntax: find df1 node under Diagram -> Data Flows in treeStage, check Protocol & ProtocolLayers
	trees := stager.GetTreeStage().GetInstancesSorted[*tree.Tree]()
	if len(trees) == 0 {
		t.Fatalf("expected UX tree to be populated")
	}
	diagNode := findTreeNodeByName(trees[0].RootNodes, "Diag1")
	if diagNode == nil {
		t.Fatalf("expected Diag1 node in UX tree")
	}
	df1NodeInDiag := findTreeNodeByName(diagNode.Children, "A-P1-B-P1-HTTP")
	if df1NodeInDiag == nil {
		t.Fatalf("expected DataFlow node A-P1-B-P1-HTTP under Diag1")
	}
	httpNodeInDF1 := findTreeNodeByName(df1NodeInDiag.Children, "HTTP")
	if httpNodeInDF1 == nil || !httpNodeInDF1.HasCheckboxButton {
		t.Fatalf("expected HTTP protocol checkbox node under DataFlow node")
	}
	httpNodeInDF1.OnIsCheckedChanged(true)

	// Re-fetch refreshed tree nodes after commit and check REST & IP layers
	trees = stager.GetTreeStage().GetInstancesSorted[*tree.Tree]()
	diagNode = findTreeNodeByName(trees[0].RootNodes, "Diag1")
	df1NodeInDiag = findTreeNodeByName(diagNode.Children, "A-P1-B-P1-HTTP")
	httpNodeInDF1 = findTreeNodeByName(df1NodeInDiag.Children, "HTTP")
	restNode := findTreeNodeByName(httpNodeInDF1.Children, "REST")
	if restNode == nil || !restNode.HasCheckboxButton {
		t.Fatalf("expected REST protocol layer checkbox node under HTTP")
	}
	restNode.OnIsCheckedChanged(true)

	trees = stager.GetTreeStage().GetInstancesSorted[*tree.Tree]()
	diagNode = findTreeNodeByName(trees[0].RootNodes, "Diag1")
	df1NodeInDiag = findTreeNodeByName(diagNode.Children, "A-P1-B-P1-HTTP")
	httpNodeInDF1 = findTreeNodeByName(df1NodeInDiag.Children, "HTTP")
	ipNode := findTreeNodeByName(httpNodeInDF1.Children, "IP")
	if ipNode == nil || !ipNode.HasCheckboxButton {
		t.Fatalf("expected IP protocol layer checkbox node under HTTP")
	}
	ipNode.OnIsCheckedChanged(true)

	svgObj := stager.GetSvgObject()
	var rectNames []string
	for _, r := range svgObj.Layers[0].Rects {
		rectNames = append(rectNames, r.Name)
		if r.Name == "A-P1-HTTP" {
			if len(r.RectAnchoredTexts) == 0 || r.RectAnchoredTexts[0].Content != "P1" {
				t.Fatalf("expected compact canvas port label %q on A-P1-HTTP, got %v", "P1", r.RectAnchoredTexts)
			}
			if r.RectAnchoredTexts[0].StrokeWidth != 0 || r.RectAnchoredTexts[0].FontSize != "11px" {
				t.Fatalf("expected light port typography (StrokeWidth=0, FontSize=11px), got StrokeWidth=%v FontSize=%q",
					r.RectAnchoredTexts[0].StrokeWidth, r.RectAnchoredTexts[0].FontSize)
			}
		}
		if r.Name == "HTTP" {
			if len(r.RectAnchoredTexts) == 0 || r.RectAnchoredTexts[0].Content != "«HTTP»" {
				t.Fatalf("expected subtle guillemet protocol label %q, got %v", "«HTTP»", r.RectAnchoredTexts)
			}
		}
	}
	for _, expected := range []string{"HTTP", "REST", "IP"} {
		if !slices.Contains(rectNames, expected) {
			t.Fatalf("expected SVG rect %q for DataFlow protocol/layers, got %v", expected, rectNames)
		}
	}
	if slices.Contains(rectNames, "Ethernet") {
		t.Fatalf("did not expect unchecked layer Ethernet in SVG rects, got %v", rectNames)
	}

	// 4. Rename Protocol "HTTP" -> "HTTPS": Port, DataFlow, and SVG rect names update automatically
	protoHTTP.Name = "HTTPS"
	stage.Commit()

	if portA1.Name != "A-P1-HTTPS" || portB1.Name != "B-P1-HTTPS" {
		t.Fatalf("expected port names updated to HTTPS, got %q, %q", portA1.Name, portB1.Name)
	}
	if df1.Name != "A-P1-B-P1-HTTPS" {
		t.Fatalf("expected df1 name updated to A-P1-B-P1-HTTPS, got %q", df1.Name)
	}

	svgObj = stager.GetSvgObject()
	rectNames = nil
	for _, r := range svgObj.Layers[0].Rects {
		rectNames = append(rectNames, r.Name)
	}
	if !slices.Contains(rectNames, "HTTPS") {
		t.Fatalf("expected SVG rect HTTPS after rename, got %v", rectNames)
	}

	// 5. Change portB1.Protocol from HTTPS -> gRPC:
	//    - df1.Protocol and portA1.Protocol synchronize to gRPC
	//    - Port and DataFlow names regenerate to A-P1-gRPC, B-P1-gRPC, A-P1-B-P1-gRPC
	//    - Stale HTTPS ProtocolShape and REST ProtocolLayerShape are automatically cleaned up;
	//      IP ProtocolLayerShape remains valid because gRPC also includes IP!
	portB1.Protocol = protoGRPC
	stage.Commit()

	if df1.Protocol != protoGRPC || portA1.Protocol != protoGRPC {
		t.Fatalf("expected df1 and portA1 synchronized to gRPC after portB1 edit, got df1=%v portA1=%v", df1.Protocol, portA1.Protocol)
	}
	if portA1.Name != "A-P1-gRPC" || portB1.Name != "B-P1-gRPC" || df1.Name != "A-P1-B-P1-gRPC" {
		t.Fatalf("expected names regenerated to gRPC, got portA1=%q portB1=%q df1=%q", portA1.Name, portB1.Name, df1.Name)
	}
	if len(diag.Protocol_Shapes) != 0 {
		t.Fatalf("expected stale HTTPS ProtocolShape removed from diagram, got %d", len(diag.Protocol_Shapes))
	}
	if len(diag.ProtocolLayer_Shapes) != 1 || diag.ProtocolLayer_Shapes[0].ProtocolLayer != layerIP {
		t.Fatalf("expected only shared IP ProtocolLayerShape retained, got %v", diag.ProtocolLayer_Shapes)
	}

	// 6. Clear df1.Protocol -> nil: portA1 and portB1 clear to nil, names revert to A-P1, B-P1, A-P1-B-P1
	df1.Protocol = nil
	stage.Commit()

	if portA1.Protocol != nil || portB1.Protocol != nil {
		t.Fatalf("expected portA1 and portB1 protocol cleared to nil, got %v, %v", portA1.Protocol, portB1.Protocol)
	}
	if portA1.Name != "A-P1" || portB1.Name != "B-P1" || df1.Name != "A-P1-B-P1" {
		t.Fatalf("expected base names after clearing protocol, got portA1=%q portB1=%q df1=%q", portA1.Name, portB1.Name, df1.Name)
	}
	if len(diag.ProtocolLayer_Shapes) != 0 {
		t.Fatalf("expected ProtocolLayer_Shapes cleared when DataFlow.Protocol is nil, got %d", len(diag.ProtocolLayer_Shapes))
	}

	// 7. Enable IsPortAndDataFlowProtocolConsistencyRelaxed via Library Probe form:
	//    StartPort, EndPort, and DataFlow can now hold distinct Protocols without overwriting each other!
	stack.Probe.FillUpFormFromGongstruct(rootLib, "Library")
	formStage := stack.Probe.GetFormStage()
	fg := formStage.GetInstancesSorted[*form.FormGroup]()[0]
	var foundRelaxCheckbox bool
	for _, fd := range fg.FormDivs {
		if fd.Name == "IsPortAndDataFlowProtocolConsistencyRelaxed" && len(fd.CheckBoxs) > 0 && fd.CheckBoxs[0] != nil {
			fd.CheckBoxs[0].Value = true
			foundRelaxCheckbox = true
			break
		}
	}
	if !foundRelaxCheckbox {
		t.Fatalf("expected IsPortAndDataFlowProtocolConsistencyRelaxed checkbox in Library form")
	}
	formStage.Commit()
	fg.OnSave.OnSave()

	if !rootLib.IsPortAndDataFlowProtocolConsistencyRelaxed {
		t.Fatalf("expected IsPortAndDataFlowProtocolConsistencyRelaxed to be true")
	}

	protoTCP := (&models.Protocol{Name: "TCP"}).Stage(stage)
	portA1.Protocol = protoHTTP // "HTTPS"
	portB1.Protocol = protoGRPC // "gRPC"
	df1.Protocol = protoTCP     // "TCP"
	stage.Commit()

	if portA1.Protocol != protoHTTP || portB1.Protocol != protoGRPC || df1.Protocol != protoTCP {
		t.Fatalf("expected independent protocols preserved when relaxed, got portA1=%v portB1=%v df1=%v",
			portA1.Protocol, portB1.Protocol, df1.Protocol)
	}
	if portA1.Name != "A-P1-HTTPS" || portB1.Name != "B-P1-gRPC" || df1.Name != "A-P1-B-P1-TCP" {
		t.Fatalf("expected independent auto-generated names when relaxed, got portA1=%q portB1=%q df1=%q",
			portA1.Name, portB1.Name, df1.Name)
	}
}
