// GenerateDSMScaffold generates the DSM Stager, Tree UI, Dual Go/XML Drop-in & Export,
// and XSD Semantic Constraint Enforcement files in ctx.TargetModelsDir.
func (ctx *MultiGenerateContext) GenerateDSMScaffold() error {
	if err := ctx.generateStagerFile(); err != nil {
		return err
	}
	if err := ctx.generateStagerCreateViewsFile(); err != nil {
		return err
	}
	if err := ctx.generateStagerTreeFile(); err != nil {
		return err
	}
	if err := ctx.generateStagerXMLIOFile(); err != nil {
		return err
	}
	if err := ctx.generateStagerEnforceSemanticFile(); err != nil {
		return err
	}
	return nil
}

func (ctx *MultiGenerateContext) subPkgImportsCode() (importsBlock string, blankVarsBlock string) {
	var impLines []string
	var blankLines []string

	var aliases []string
	pkgByAlias := make(map[string]*TargetPackage)
	for _, pkg := range ctx.SG.TargetPackages {
		if !pkg.IsRoot && len(ctx.StructsByPkg[pkg]) > 0 {
			aliases = append(aliases, pkg.ImportAlias)
			pkgByAlias[pkg.ImportAlias] = pkg
		}
	}
	slices.Sort(aliases)

	for _, alias := range aliases {
		pkg := pkgByAlias[alias]
		if alias == filepath.Base(pkg.ImportPath) {
			impLines = append(impLines, fmt.Sprintf("\t%q", pkg.ImportPath))
		} else {
			impLines = append(impLines, fmt.Sprintf("\t%s %q", alias, pkg.ImportPath))
		}
		blankLines = append(blankLines, fmt.Sprintf("\t_ *%s.%s", alias, ctx.StructsByPkg[pkg][0].GoName))
	}
	return strings.Join(impLines, "\n"), strings.Join(blankLines, "\n")
}

