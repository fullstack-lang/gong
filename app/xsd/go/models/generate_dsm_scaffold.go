func detectRootXMLElementLocalName(data []byte) string {
	dec := xml.NewDecoder(bytes.NewReader(data))
	for {
		tok, err := dec.Token()
		if err != nil {
			if err == io.EOF {
				break
			}
			return ""
		}
		if se, ok := tok.(xml.StartElement); ok {
			return se.Name.Local
		}
	}
	return ""
}

func ensureUTF8XML(data []byte) []byte {
	if len(data) >= 2 {
		// Check UTF-16 LE BOM (FF FE) or UTF-16 BE BOM (FE FF)
		if data[0] == 0xFF && data[1] == 0xFE {
			u16s := make([]uint16, (len(data)-2)/2)
			for i := range u16s {
				u16s[i] = uint16(data[2+2*i]) | (uint16(data[2+2*i+1]) << 8)
			}
			runes := utf16.Decode(u16s)
			out := string(runes)
			out = strings.Replace(out, "encoding=\"UTF-16\"", "encoding=\"UTF-8\"", 1)
			out = strings.Replace(out, "encoding='UTF-16'", "encoding='UTF-8'", 1)
			return []byte(out)
		}
		if data[0] == 0xFE && data[1] == 0xFF {
			u16s := make([]uint16, (len(data)-2)/2)
			for i := range u16s {
				u16s[i] = (uint16(data[2+2*i]) << 8) | uint16(data[2+2*i+1])
			}
			runes := utf16.Decode(u16s)
			out := string(runes)
			out = strings.Replace(out, "encoding=\"UTF-16\"", "encoding=\"UTF-8\"", 1)
			out = strings.Replace(out, "encoding='UTF-16'", "encoding='UTF-8'", 1)
			return []byte(out)
		}
	}
	return data
}

type goFileUploadCallback struct {
	stager *Stager
}

func (cb *goFileUploadCallback) OnFileUpload(loadedFile *load.FileToUpload) error {
	decodedBytes, err := base64.StdEncoding.DecodeString(loadedFile.Base64EncodedContent)
	if err != nil {
		log.Printf("Failed decoding base64 Go file: %%v", err)
		return err
	}

	cb.stager.stage.Reset()
	if err := cb.stager.stage.ParseAstString(string(decodedBytes), true); err != nil {
		log.Printf("Failed parsing Multi-Stage Go AST: %%v", err)
		return err
	}

	ext := filepath.Ext(loadedFile.Name)
	cb.stager.fileName = strings.TrimSuffix(loadedFile.Name, ext)
	cb.stager.stage.Commit()
	return nil
}

