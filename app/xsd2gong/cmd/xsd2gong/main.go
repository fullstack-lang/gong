package main

import (
	"flag"
	"fmt"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"github.com/fullstack-lang/gong/app/xsd2gong/pkg/depgraph"
	"github.com/fullstack-lang/gong/app/xsd2gong/pkg/emit_models"
	"github.com/fullstack-lang/gong/app/xsd2gong/pkg/emit_semantics"
	"github.com/fullstack-lang/gong/app/xsd2gong/pkg/emit_xml"
	"github.com/fullstack-lang/gong/app/xsd2gong/pkg/xsdloader"
	"golang.org/x/mod/modfile"
)

func main() {
	var xsdPath string
	var outModelsDir string
	var runGong bool

	flag.StringVar(&xsdPath, "xsd", "", "Path to root XSD file (e.g. musicxml.xsd)")
	flag.StringVar(&outModelsDir, "out", "", "Path to output go/models directory")
	flag.BoolVar(&runGong, "gong", true, "Run gong generate on the emitted packages")
	flag.Parse()

	if xsdPath == "" || outModelsDir == "" {
		log.Fatalf("Usage: xsd2gong -xsd <path/to/schema.xsd> -out <path/to/go/models> [-gong=true]")
	}

	absXSD, err := filepath.Abs(xsdPath)
	if err != nil {
		log.Fatalf("resolving xsd path: %v", err)
	}
	absOut, err := filepath.Abs(outModelsDir)
	if err != nil {
		log.Fatalf("resolving out path: %v", err)
	}

	// 1. Load XSD schema set (root + imports/includes)
	log.Printf("[xsd2gong] Loading XSD schema set from %s...", absXSD)
	schemaSet, err := xsdloader.Load(absXSD)
	if err != nil {
		log.Fatalf("loading XSDs: %v", err)
	}
	log.Printf("[xsd2gong] Loaded %d schema file(s)", len(schemaSet.Schemas))

	// 2. Build dependency graph & break cycles via Tarjan's SCC
	log.Printf("[xsd2gong] Partitioning types and running Tarjan SCC cycle-breaker...")
	graph, err := depgraph.Build(schemaSet)
	if err != nil {
		log.Fatalf("building dependency graph: %v", err)
	}
	var pkgNames []string
	for _, p := range graph.TopologicalOrd {
		pkgNames = append(pkgNames, p.Name)
	}
	log.Printf("[xsd2gong] Topological package order (leaves -> root): %s", strings.Join(pkgNames, " -> "))

	// 3. Compute Go module import path for outModelsDir
	baseImportPath, err := computeImportPath(absOut)
	if err != nil {
		log.Fatalf("computing import path for %s: %v", absOut, err)
	}
	log.Printf("[xsd2gong] Base import path: %s", baseImportPath)

	em, err := emit_models.Prepare(graph, baseImportPath, false)
	if err != nil {
		log.Fatalf("preparing models: %v", err)
	}

	// Ensure parent go directory exists for gong generate
	parentGoDir := filepath.Dir(absOut)
	if err := os.MkdirAll(parentGoDir, 0o755); err != nil {
		log.Fatalf("mkdir %s: %v", parentGoDir, err)
	}

	// Clean any old files in absOut that might have had package score
	_ = os.Remove(filepath.Join(absOut, "models_xml.go"))
	_ = os.Remove(filepath.Join(absOut, "models_semantics.go"))

	// Emit root `package models` in absOut that imports the top-level XSD package ("score")
	// so `gong generate` executed in `go/models` discovers the entire DAG (`xlink` -> ... -> `score`).
	topPkg := em.OrderedPkgs[len(em.OrderedPkgs)-1]
	rootModelsGo := fmt.Sprintf(`// Code generated by xsd2gong. DO NOT EDIT.
package models

import (
	%s %q
)

type MusicXMLDocument struct {
	Name          string
	ScorePartwise *%s.ScorePartwise
	ScoreTimewise *%s.ScoreTimewise
}
`, topPkg.Name, topPkg.ImportPath, topPkg.Name, topPkg.Name)
	if err := os.WriteFile(filepath.Join(absOut, "models.go"), []byte(rootModelsGo), 0o644); err != nil {
		log.Fatalf("writing root models.go: %v", err)
	}
	rootDocsGo := "// Code generated by xsd2gong. DO NOT EDIT.\npackage models\n"
	if err := os.WriteFile(filepath.Join(absOut, "docs.go"), []byte(rootDocsGo), 0o644); err != nil {
		log.Fatalf("writing root docs.go: %v", err)
	}

	// 4. Emit models.go and docs.go for each package first (without referencing Gong generated functions yet)
	for _, ep := range em.OrderedPkgs {
		pkgDir := filepath.Join(absOut, ep.DirRel)
		if err := os.MkdirAll(pkgDir, 0o755); err != nil {
			log.Fatalf("mkdir %s: %v", pkgDir, err)
		}

		// Remove any stale models_semantics.go or orchestrator before running `gong generate`
		// so `gong generate`'s type-checker doesn't fail on not-yet-generated `Stage` types!
		_ = os.Remove(filepath.Join(pkgDir, "models_semantics.go"))

		modelsContent := emit_models.RenderModelsFile(ep)
		if err := os.WriteFile(filepath.Join(pkgDir, "models.go"), []byte(modelsContent), 0o644); err != nil {
			log.Fatalf("writing models.go in %s: %v", pkgDir, err)
		}

		docsContent := emit_models.RenderDocsFile(ep)
		if err := os.WriteFile(filepath.Join(pkgDir, "docs.go"), []byte(docsContent), 0o644); err != nil {
			log.Fatalf("writing docs.go in %s: %v", pkgDir, err)
		}

		xmlContent := emit_xml.RenderPackageXMLFile(ep, em)
		if err := os.WriteFile(filepath.Join(pkgDir, "models_xml.go"), []byte(xmlContent), 0o644); err != nil {
			log.Fatalf("writing models_xml.go in %s: %v", pkgDir, err)
		}
	}

	// Remove orchestrator dir before running `gong generate` so `gong generate` cleanly generates all stages first
	orchDir := filepath.Join(absOut, "orchestrator")
	_ = os.RemoveAll(orchDir)

	// 5. Run `gong generate` on the root models directory (which automatically discovers and generates
	// all sub-packages in topological order via DiscoverModelDependencies!)
	if runGong {
		log.Printf("[xsd2gong] Running `gong generate --skipGoModCommands --skipGoBuild` in %s...", absOut)
		cmd := exec.Command("go", "run", "github.com/fullstack-lang/gong/go/cmd/gong", "generate", "--skipGoModCommands", "--skipGoBuild")
		cmd.Dir = absOut
		cmd.Stdout = os.Stdout
		cmd.Stderr = os.Stderr
		if err := cmd.Run(); err != nil {
			log.Fatalf("gong generate failed: %v", err)
		}
	}

	// 6. Now that `zzz_gong*.go` and `Stage` types exist in every package, emit `models_semantics.go`
	// in each package and emit the `orchestrator` package (`stages.go`, `xml_io.go`, `semantics.go`)!
	for _, ep := range em.OrderedPkgs {
		pkgDir := filepath.Join(absOut, ep.DirRel)
		semContent := emit_semantics.RenderPackageSemanticsFile(ep, em)
		if err := os.WriteFile(filepath.Join(pkgDir, "models_semantics.go"), []byte(semContent), 0o644); err != nil {
			log.Fatalf("writing models_semantics.go in %s: %v", pkgDir, err)
		}
	}

	if err := os.MkdirAll(orchDir, 0o755); err != nil {
		log.Fatalf("mkdir %s: %v", orchDir, err)
	}
	if err := os.WriteFile(filepath.Join(orchDir, "stages.go"), []byte(emit_xml.RenderOrchestratorStages(em)), 0o644); err != nil {
		log.Fatalf("writing orchestrator/stages.go: %v", err)
	}
	if err := os.WriteFile(filepath.Join(orchDir, "xml_io.go"), []byte(emit_xml.RenderOrchestratorXMLIO(em)), 0o644); err != nil {
		log.Fatalf("writing orchestrator/xml_io.go: %v", err)
	}
	if err := os.WriteFile(filepath.Join(orchDir, "semantics.go"), []byte(emit_semantics.RenderOrchestratorSemantics(em)), 0o644); err != nil {
		log.Fatalf("writing orchestrator/semantics.go: %v", err)
	}

	log.Printf("[xsd2gong] Successfully generated multi-package Gong models and orchestrator in %s", absOut)
}

func computeImportPath(absDir string) (string, error) {
	curr := absDir
	for range 15 {
		goModFile := filepath.Join(curr, "go.mod")
		if buf, err := os.ReadFile(goModFile); err == nil {
			mf, err := modfile.Parse(goModFile, buf, nil)
			if err != nil || mf.Module == nil {
				return "", fmt.Errorf("parsing %s: %w", goModFile, err)
			}
			rel, err := filepath.Rel(curr, absDir)
			if err != nil {
				return "", err
			}
			return filepath.ToSlash(filepath.Join(mf.Module.Mod.Path, rel)), nil
		}
		parent := filepath.Dir(curr)
		if parent == curr {
			break
		}
		curr = parent
	}
	return "", fmt.Errorf("go.mod not found above %s", absDir)
}

