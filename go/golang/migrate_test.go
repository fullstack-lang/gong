func TestMigrateStageSource(t *testing.T) {
	input := `// file generated by gong
package main

import (
	"time"

	"github.com/fullstack-lang/gong/test/test2/go/models"
)

// declaration of instances to stage
var (
	_ time.Time
	_ *models.Stage
)

// function will stage objects
func _(stage *models.Stage) {

	// Declarations of staged instances
	__A__000000_A1 := (&models.A{Name: "A1"}).Stage(stage)
	__B__000000_B1 := (&models.B{Name: "B1"}).Stage(stage)

	// Setup of values
	__A__000000_A1.Name = "A1"
	__A__000000_A1.NumberField = 42
	__A__000000_A1.Foo = 100
	__A__000000_A1.Bar = 3.14
	__A__000000_A1.Zorgh = "Test Single Stage"
	__B__000000_B1.Name = "B1"

	// Setup of pointers
	__A__000000_A1.B = __B__000000_B1
}
`

	out, err := MigrateStageSource([]byte(input), "", "test2/data/stage.go")
	if err != nil {
		t.Fatalf("MigrateStageSource failed: %v", err)
	}

	// Assertions on the output
	if !strings.Contains(out, `func _(stageSet *__stage_0__.StageSet)`) {
		t.Errorf("expected StageSet function header, got:\n%s", out)
	}
	if !strings.Contains(out, `__stage_0__ "github.com/fullstack-lang/gong/test/test2/go/models"`) {
		t.Errorf("expected __stage_0__ models import, got:\n%s", out)
	}
	if !strings.Contains(out, `_ *__stage_0__.Stage`) {
		t.Errorf("expected dummy declaration _ *__stage_0__.Stage, got:\n%s", out)
	}
	if !strings.Contains(out, `__stage_0__A__00000000_ := (&__stage_0__.A{Name: "A1"}).Stage(stageSet.Stage)`) {
		t.Errorf("expected migrated A declaration, got:\n%s", out)
	}
	if !strings.Contains(out, `__stage_0__B__00000000_ := (&__stage_0__.B{Name: "B1"}).Stage(stageSet.Stage)`) {
		t.Errorf("expected migrated B declaration, got:\n%s", out)
	}
	if !strings.Contains(out, `__stage_0__A__00000000_.NumberField = 42`) {
		t.Errorf("expected migrated value initialization, got:\n%s", out)
	}
	if !strings.Contains(out, `__stage_0__A__00000000_.B = __stage_0__B__00000000_`) {
		t.Errorf("expected migrated pointer setup, got:\n%s", out)
	}
	if !strings.Contains(out, `Phase 1: Declarations`) || !strings.Contains(out, `Phase 2: Value Initializations`) || !strings.Contains(out, `Phase 3: Pointer Setups`) {
		t.Errorf("expected 3-phase comments, got:\n%s", out)
	}

	// Test idempotency: migrating the output should succeed and be a no-op
	out2, err := MigrateStageSource([]byte(out), "", "test2/data/stageset.go")
	if err != nil {
		t.Fatalf("MigrateStageSource on already migrated code failed: %v", err)
	}
	if !strings.Contains(out2, `func _(stageSet *__stage_0__.StageSet)`) {
		t.Errorf("expected idempotent StageSet output, got:\n%s", out2)
	}
}

func TestMigrateStageWithAppends(t *testing.T) {
	input := `package main

import (
	"slices"
	"time"

	"github.com/fullstack-lang/gong/test/test2/go/models"
)

var (
	_ time.Time
	_ = slices.Index[[]int, int]
)

func _(stage *models.Stage) {
	__A__00000000_ := (&models.A{Name: "A1"}).Stage(stage)
	__B__00000000_ := (&models.B{Name: "B1"}).Stage(stage)
	__B__00000001_ := (&models.B{Name: "B2"}).Stage(stage)

	__A__00000000_.Name = "A1"
	__B__00000000_.Name = "B1"
	__B__00000001_.Name = "B2"

	__A__00000000_.Bs = append(__A__00000000_.Bs, __B__00000000_)
	__A__00000000_.Bs = append(__A__00000000_.Bs, __B__00000001_)
}
`

	out, err := MigrateStageSource([]byte(input), "", "test2/data/stage.go")
	if err != nil {
		t.Fatalf("MigrateStageSource failed: %v", err)
	}

	if !strings.Contains(out, `__stage_0__A__00000000_.Bs = append(__stage_0__A__00000000_.Bs, __stage_0__B__00000000_)`) {
		t.Errorf("expected migrated slice append for B1, got:\n%s", out)
	}
	if !strings.Contains(out, `__stage_0__A__00000000_.Bs = append(__stage_0__A__00000000_.Bs, __stage_0__B__00000001_)`) {
		t.Errorf("expected migrated slice append for B2, got:\n%s", out)
	}
}

func TestMigrateStageFile(t *testing.T) {
	inputPath := "../../test/test2/go/cmd/test2/data/stage.go"
	outPath := t.TempDir() + "/stageset.go"

	resPath, err := MigrateStageFile(inputPath, outPath, "", false)
	if err != nil {
		t.Fatalf("MigrateStageFile failed: %v", err)
	}
	if resPath != outPath {
		t.Errorf("expected output path %s, got %s", outPath, resPath)
	}

	data, err := os.ReadFile(outPath)
	if err != nil {
		t.Fatalf("failed to read migrated file: %v", err)
	}

	content := string(data)
	if !strings.Contains(content, `func _(stageSet *__stage_0__.StageSet)`) {
		t.Errorf("expected StageSet function in migrated file, got:\n%s", content)
	}
	if !strings.Contains(content, `__stage_0__A__00000000_ := (&__stage_0__.A{Name: `) {
		t.Errorf("expected migrated instance A1, got:\n%s", content)
	}
	if !strings.Contains(content, `__stage_0__B__00000000_ := (&__stage_0__.B{Name: `) {
		t.Errorf("expected migrated instance B1, got:\n%s", content)
	}
	if !strings.Contains(content, `__stage_0__A__00000000_.B = __stage_0__B__00000000_`) {
		t.Errorf("expected migrated pointer A.B, got:\n%s", content)
	}
}

