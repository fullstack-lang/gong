const sampleStageCode = `// file generated by gong
package main

import (
	"slices"
	"time"

	"github.com/fullstack-lang/gong/test/test3/go/models"
)

var (
	_ time.Time
	_ = slices.Index[[]int, int]
)

func _(stage *models.Stage) {

	// insertion point for declaration of instances to stage

	__Diagram__00000000_ := (&models.Diagram{Name: "Flight Plan Flow"}).Stage(stage)
	__Task__00000000_ := (&models.Task{Name: "Submit Flight Plan"}).Stage(stage)
	__TaskShape__00000000_ := (&models.TaskShape{Name: "Flight Plan Flow-Submit Flight Plan"}).Stage(stage)

	// insertion point for initialization of values

	__Diagram__00000000_.Name = "Flight Plan Flow"
	__Diagram__00000000_.Description = ""
	__Diagram__00000000_.ComputedStart, _ = time.Parse("2006-01-02 15:04:05.999999999 -0700 MST", "2024-01-01 12:00:00 +0000 UTC")

	__Task__00000000_.Name = "Submit Flight Plan"
	__Task__00000000_.Description = "Originator creates a new flight plan and transmits it via ARO."

	__TaskShape__00000000_.Name = "Flight Plan Flow-Submit Flight Plan"
}
`

func TestScrambleStageSource_WordsMode(t *testing.T) {
	opts := ScrambleOptions{
		Mode: ScrambleModeWords,
		Salt: "test-salt-12345",
	}

	scrambledBytes, err := ScrambleStageSource([]byte(sampleStageCode), opts)
	if err != nil {
		t.Fatalf("ScrambleStageSource failed: %v", err)
	}

	scrambled := string(scrambledBytes)

	// 1. Output must parse without Go syntax errors
	fset := token.NewFileSet()
	_, err = parser.ParseFile(fset, "scrambled.go", scrambled, parser.ParseComments)
	if err != nil {
		t.Fatalf("Scrambled output is invalid Go code:\n%s\nError: %v", scrambled, err)
	}

	// 2. Original confidential text must not be present
	if strings.Contains(scrambled, "Submit Flight Plan") {
		t.Errorf("original string 'Submit Flight Plan' is still present in scrambled code")
	}
	if strings.Contains(scrambled, "Flight Plan Flow") {
		t.Errorf("original string 'Flight Plan Flow' is still present in scrambled code")
	}
	if strings.Contains(scrambled, "Originator creates a new flight plan") {
		t.Errorf("original description is still present in scrambled code")
	}

	// 3. time.Parse layout and value must be preserved intact
	if !strings.Contains(scrambled, "2006-01-02 15:04:05.999999999 -0700 MST") {
		t.Errorf("time.Parse layout was modified")
	}
	if !strings.Contains(scrambled, "2024-01-01 12:00:00 +0000 UTC") {
		t.Errorf("time.Parse timestamp was modified")
	}

	// 4. Empty string must remain empty
	if !strings.Contains(scrambled, `__Diagram__00000000_.Description = ""`) &&
		!strings.Contains(scrambled, "__Diagram__00000000_.Description = ``") {
		t.Errorf("empty description was altered")
	}

	// 5. Check referential integrity:
	// Diagram name in declaration and assignment must match
	lines := strings.Split(scrambled, "\n")
	var declDiagName, assignDiagName string
	var declTaskName, assignTaskName string
	var shapeName string

	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "__Diagram__00000000_ :=") {
			declDiagName = extractLiteralBetween(trimmed, "Name: `", "`")
		} else if strings.HasPrefix(trimmed, "__Diagram__00000000_.Name =") {
			assignDiagName = extractLiteralBetween(trimmed, "= `", "`")
		} else if strings.HasPrefix(trimmed, "__Task__00000000_ :=") {
			declTaskName = extractLiteralBetween(trimmed, "Name: `", "`")
		} else if strings.HasPrefix(trimmed, "__Task__00000000_.Name =") {
			assignTaskName = extractLiteralBetween(trimmed, "= `", "`")
		} else if strings.HasPrefix(trimmed, "__TaskShape__00000000_.Name =") {
			shapeName = extractLiteralBetween(trimmed, "= `", "`")
		}
	}

	if declDiagName == "" || declDiagName != assignDiagName {
		t.Errorf("Diagram name mismatch: decl=%q, assign=%q", declDiagName, assignDiagName)
	}
	if declTaskName == "" || declTaskName != assignTaskName {
		t.Errorf("Task name mismatch: decl=%q, assign=%q", declTaskName, assignTaskName)
	}

	// In words mode, compound shape name must equal <scrambled_diag>-<scrambled_task>
	expectedShapeName := declDiagName + "-" + declTaskName
	if shapeName != expectedShapeName {
		t.Errorf("Compound shape name %q does not match expected %q", shapeName, expectedShapeName)
	}

	// 6. Comments must be preserved
	if !strings.Contains(scrambled, "// insertion point for declaration of instances to stage") {
		t.Errorf("Stage comments were lost during formatting")
	}
}

func TestScrambleStageSource_TokensMode(t *testing.T) {
	opts := ScrambleOptions{
		Mode: ScrambleModeTokens,
		Salt: "token-salt-999",
	}

	scrambledBytes, err := ScrambleStageSource([]byte(sampleStageCode), opts)
	if err != nil {
		t.Fatalf("ScrambleStageSource failed: %v", err)
	}

	scrambled := string(scrambledBytes)

	// Verify tokens format
	if !strings.Contains(scrambled, "Scrambled_") {
		t.Errorf("Tokens mode output does not contain 'Scrambled_' tokens:\n%s", scrambled)
	}

	// Syntax check
	fset := token.NewFileSet()
	_, err = parser.ParseFile(fset, "scrambled_tokens.go", scrambled, parser.ParseComments)
	if err != nil {
		t.Fatalf("Scrambled tokens output has syntax errors: %v", err)
	}
}

func TestScrambleStageSource_RandomSaltDifferentOutputs(t *testing.T) {
	opts := ScrambleOptions{
		Mode: ScrambleModeWords,
		// No salt -> generates fresh 256-bit salt each run
	}

	run1, err := ScrambleStageSource([]byte(sampleStageCode), opts)
	if err != nil {
		t.Fatalf("run1 failed: %v", err)
	}

	run2, err := ScrambleStageSource([]byte(sampleStageCode), opts)
	if err != nil {
		t.Fatalf("run2 failed: %v", err)
	}

	if string(run1) == string(run2) {
		t.Fatalf("Two runs without salt produced identical outputs! Random salt is not working.")
	}
}

func TestScrambleStageFile_FileOperations(t *testing.T) {
	tempDir := t.TempDir()
	inputPath := filepath.Join(tempDir, "input_stage.go")
	if err := os.WriteFile(inputPath, []byte(sampleStageCode), 0o644); err != nil {
		t.Fatalf("failed to write input file: %v", err)
	}

	// Test default output path (<input>-scrambled.go)
	opts := ScrambleOptions{Mode: ScrambleModeWords, Salt: "salt1"}
	outPath, err := ScrambleStageFile(inputPath, opts)
	if err != nil {
		t.Fatalf("ScrambleStageFile failed: %v", err)
	}

	expectedOutPath := filepath.Join(tempDir, "input_stage-scrambled.go")
	if outPath != expectedOutPath {
		t.Errorf("expected outPath %s, got %s", expectedOutPath, outPath)
	}

	if _, err := os.Stat(outPath); os.IsNotExist(err) {
		t.Fatalf("output file does not exist: %s", outPath)
	}

	// Test in-place
	inPlaceOpts := ScrambleOptions{Mode: ScrambleModeWords, Salt: "salt2", InPlace: true}
	outPathInPlace, err := ScrambleStageFile(inputPath, inPlaceOpts)
	if err != nil {
		t.Fatalf("ScrambleStageFile in-place failed: %v", err)
	}
	if outPathInPlace != inputPath {
		t.Errorf("expected outPath %s, got %s", inputPath, outPathInPlace)
	}

	content, _ := os.ReadFile(inputPath)
	if strings.Contains(string(content), "Submit Flight Plan") {
		t.Errorf("file was not scrambled in-place")
	}
}

func extractLiteralBetween(s, prefix, suffix string) string {
	idx := strings.Index(s, prefix)
	if idx == -1 {
		return ""
	}
	rest := s[idx+len(prefix):]
	endIdx := strings.Index(rest, suffix)
	if endIdx == -1 {
		return ""
	}
	return rest[:endIdx]
}
